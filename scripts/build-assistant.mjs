import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { PROJECT } from './project-config.mjs';

const base = new URL('../assistant/', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('bundle-sections.json', base), 'utf8'));
const header = '/* MRB Recording Assistant — classic script bundle\n * Generated by scripts/build-assistant.mjs. Sources: assistant/js/*.js\n */\n\n';
const digest = s => createHash('sha256').update(s.replace(/\r\n?/g, '\n').trim()).digest('hex');
const sections = [];
for (const entry of manifest.sections) {
  const sourceUrl = new URL(`js/${entry.name}`, base);
  let source = await readFile(sourceUrl, 'utf8');
  if (entry.name === '01-config.js') {
    source = source.replace(/  var PROJECT = .*?;\n/, `  var PROJECT = ${JSON.stringify(PROJECT)};\n`);
    await writeFile(sourceUrl, source);
  }
  sections.push({ name: entry.name, source });
}
await writeFile(new URL('app.js', base), header + sections.map(s => `/* ==== ${s.name} ==== */\n${s.source}`).join('\n'));
await writeFile(new URL('bundle-sections.json', base), JSON.stringify({ version: 1, algorithm: 'sha256-normalized-v1', preamble: { sha256: digest(header) }, sections: sections.map(s => ({ name: s.name, sha256: digest(s.source) })) }, null, 2) + '\n');
console.log('Rebuilt Recording Assistant with the versioned project facts.');
